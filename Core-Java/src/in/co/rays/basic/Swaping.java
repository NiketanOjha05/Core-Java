package in.co.rays.basic;

public class Swaping {
	
	public static void main(String[] args) {
		
		
		int a = 10;
		int b = 20;
		int c;

		System.out.println("a = " + a);
		System.out.println("b = " + b);
		System.out.println("c =" );
		
		// swaping

		c = a; // c = 10;
		a = b; // a = 20;
		b = c; // b = 10;
		
		System.out.println("a = " + a);
		System.out.println("b = " + b);
		System.out.println("c = " + c);
		
	}

}
