package in.co.rays.basic;

public class SwitchCase {
	public static void main(String[] args) {
		
	String day = "Sunday";
	
	switch (day) {
	case "Monday":
		System.out.println("first day of weak");
		break;
	case "Tuesday":
		System.out.println("second day of waek");
		break;
	case "Wednesday":
		System.out.println("third day of weak");
		break;
	case "Thursday":
		System.out.println("fourth day of weak");
		break;
	case "Friday":
		System.out.println("fifth day of weak");
		break;
	case "Saturday":
		System.out.println("sixth day of weak");
		break;
	case "Sunday":
		System.out.println("holiday");
		break;
	}
	}

}
