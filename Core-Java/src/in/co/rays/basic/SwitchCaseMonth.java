package in.co.rays.basic;

public class SwitchCaseMonth {
	public static void main(String[] args) {
		
		String month = "October";
		
		switch ( month) {
		case "January":
			System.out.println("1st month of year");
			break;
		case "Febuary":
			System.out.println("2nd month of year");
			break;
		case "March":
			System.out.println("3rd month of year");
			break;
		case "April":
			System.out.println("4th month of year");
			break;
		case "May":
			System.out.println("5th month of year");
			break;
		case "June":
			System.out.println("6th month of year");
			break;
		case "July":
			System.out.println("7th month of year");
			break;
		case "August":
			System.out.println("8th month of year");
			break;
		case "September":
			System.out.println("9th month of year");
			break;
		case "October":
			System.out.println("10th month of year");
			break;
		case "November":
			System.out.println("11th month of year");
			break;
		case "december":
			System.out.println("last month of year");
			break;
		
		}
		
	}

}
